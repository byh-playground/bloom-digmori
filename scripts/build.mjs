import {readFileSync, mkdirSync, writeFileSync} from 'node:fs';
import {spawnSync, execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {compileCompanionAssets} from './compile-companion-assets.mjs';
process.chdir(fileURLToPath(new URL('../', import.meta.url)));
const companionAssets=await compileCompanionAssets();
const order=JSON.parse(readFileSync('src/order.json','utf8'));
const game=order.map(file=>readFileSync('src/'+file,'utf8')).join('');
const syntax=spawnSync(process.execPath,['--input-type=module','--check'],{input:game,encoding:'utf8'});
if(syntax.status!==0)throw Error(syntax.stderr);
let html=readFileSync('src/ui/shell.html','utf8').replace('<!-- DIGMORI_VECTOR_RUNTIME -->',()=>companionAssets.runtimeCode).replace('<!-- DIGMORI_GAME -->',()=>game);
html=html.replace(/<!-- DIGMORI_STYLE:([^>]+) -->/g,(_,file)=>readFileSync('src/'+file,'utf8'));
if(/<!-- DIGMORI_/.test(html))throw Error('Unresolved build marker');
const version=game.match(/\bVERSION\s*=\s*['"]([^'"]+)['"]/)?.[1];
const gamekit=game.match(/distCommit:'([a-f0-9]{40})'/)?.[1];
if(!version||!gamekit)throw Error('Missing version or pinned SDK SHA');
html=html.replaceAll('__GAMEKIT_DIST__',gamekit).replaceAll('__GAME_VERSION__',version).replaceAll('__SNAPSHOT_VERSION__',game.match(/SNAPSHOT_VERSION='([^']+)'/)[1]);
const commit=process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
mkdirSync('dist',{recursive:true});
writeFileSync('dist/index.html',html);
writeFileSync('dist/.nojekyll','');
writeFileSync('dist/build.json',JSON.stringify({commit,version,gamekit_dist_commit:gamekit,gamekit_vector_source_commit:companionAssets.gamekitSourceCommit,gamekit_vector_compiler_version:companionAssets.compilerVersion,pebble_mole_svg_sha256:companionAssets.sourceSha256,pebble_mole_curve_segments:companionAssets.curveSegments,pebble_mole_geometry_bytes:companionAssets.geometryBytes,pebble_mole_triangles:companionAssets.triangles,index_sha256:createHash('sha256').update(html).digest('hex'),built_at_utc:new Date().toISOString()},null,2)+'\n');
console.log('Built Digmori '+version+' ('+Buffer.byteLength(html)+' bytes)');
