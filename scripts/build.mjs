import {readFileSync, mkdirSync, writeFileSync} from 'node:fs';
import {spawnSync, execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
process.chdir(fileURLToPath(new URL('../', import.meta.url)));
const order=JSON.parse(readFileSync('src/order.json','utf8'));
const game=order.map(file=>readFileSync('src/'+file,'utf8')).join('');
const syntax=spawnSync(process.execPath,['--input-type=module','--check'],{input:game,encoding:'utf8'});
if(syntax.status!==0)throw Error(syntax.stderr);
let html=readFileSync('src/ui/shell.html','utf8').replace('<!-- DIGMORI_GAME -->',()=>game);
html=html.replace(/<!-- DIGMORI_STYLE:([^>]+) -->/g,(_,file)=>readFileSync('src/'+file,'utf8'));
if(/<!-- DIGMORI_/.test(html))throw Error('Unresolved build marker');
const version=game.match(/\bVERSION\s*=\s*['"]([^'"]+)['"]/)?.[1];
const gamekit=game.match(/gamekit:\{repository:'[^']+',sourceCommit:'([a-f0-9]{40})',distCommit:'([a-f0-9]{40})',manifestSha256:'([a-f0-9]{64})'/);
const vector=game.match(/vectorAssets:Object\.freeze\(\{pebbleMole:Object\.freeze\(\{url:'([^']+)',sourcePath:'([^']+)',sha256:'([a-f0-9]{64})',maxBytes:(\d+),curveSegments:(\d+)\}\)\}\)/);
if(!version||!gamekit||!vector)throw Error('Missing game version, pinned SDK manifest, or SVG asset metadata');
html=html.replaceAll('__GAMEKIT_DIST__',gamekit[2]).replaceAll('__GAME_VERSION__',version).replaceAll('__SNAPSHOT_VERSION__',game.match(/SNAPSHOT_VERSION='([^']+)'/)[1]);
const commit=process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
mkdirSync('dist',{recursive:true});
writeFileSync('dist/index.html',html);
writeFileSync('dist/.nojekyll','');
const [assetUrl,sourcePath,expectedSha256,maxBytesText,curveSegmentsText]=vector.slice(1),maxBytes=Number(maxBytesText),curveSegments=Number(curveSegmentsText);
const sourceBytes=readFileSync(sourcePath),sourceSha256=createHash('sha256').update(sourceBytes).digest('hex');
if(sourceSha256!==expectedSha256)throw Error(`SVG source SHA-256 mismatch: expected ${expectedSha256}, received ${sourceSha256}`);
if(sourceBytes.byteLength>maxBytes)throw Error(`SVG source exceeds its runtime byte limit (${sourceBytes.byteLength} > ${maxBytes})`);
const assetOutput='dist/'+assetUrl,assetDirectory=assetOutput.slice(0,assetOutput.lastIndexOf('/'));
mkdirSync(assetDirectory,{recursive:true});writeFileSync(assetOutput,sourceBytes);
writeFileSync('dist/build.json',JSON.stringify({commit,version,gamekit_source_commit:gamekit[1],gamekit_dist_commit:gamekit[2],gamekit_manifest_sha256:gamekit[3],pebble_mole_svg_path:assetUrl,pebble_mole_svg_sha256:sourceSha256,pebble_mole_curve_segments:curveSegments,index_sha256:createHash('sha256').update(html).digest('hex'),built_at_utc:new Date().toISOString()},null,2)+'\n');
console.log('Built Digmori '+version+' ('+Buffer.byteLength(html)+' bytes)');
