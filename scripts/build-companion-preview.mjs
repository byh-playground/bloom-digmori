import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
process.chdir(fileURLToPath(new URL('../',import.meta.url)));
// Reuse the repository's actual art, animation and Renderer; never boot the game App.
const files=JSON.parse(readFileSync('src/order.json','utf8')).filter(f=>f!=='runtime/boot.js');
const engine=files.map(f=>readFileSync('src/'+f,'utf8')).join('\n');
const preview=readFileSync('previews/companion-combat/preview.js','utf8');
const historical=readFileSync('previews/companion-combat/attachment-art.js','utf8');
const gamekit=engine.match(/gamekit:\{repository:'[^']+',sourceCommit:'([a-f0-9]{40})',distCommit:'([a-f0-9]{40})'/);
const rendering=engine.match(/rendering:Object\.freeze\(\{file:'([^']+)'/),vectorAssets=engine.match(/vectorAssets:Object\.freeze\(\{file:'([^']+)'/),loader=engine.match(/vectorAssetLoader:Object\.freeze\(\{file:'([^']+)'/);
const vector=engine.match(/vectorAssets:Object\.freeze\(\{pebbleMole:Object\.freeze\(\{url:'([^']+)',sourcePath:'([^']+)',sha256:'([a-f0-9]{64})',maxBytes:(\d+),curveSegments:(\d+)\}\)\}\)/);
if(!gamekit||!rendering||!vectorAssets||!loader||!vector)throw Error('Pinned GameKit SVG preview dependencies are missing');
const [assetUrl,sourcePath,sha256,maxBytes,curveSegments]=vector.slice(1);
const previewBootstrap=`const __gamekitBase='https://cdn.jsdelivr.net/gh/byh-playground/bloom-gamekit@${gamekit[2]}/';
const [__rendering,__vectorAssets,__vectorAssetLoader]=await Promise.all([import(__gamekitBase+'${rendering[1]}'),import(__gamekitBase+'${vectorAssets[1]}'),import(__gamekitBase+'${loader[1]}')]);
const previewGamekit={rendering:__rendering,vectorAssets:__vectorAssets};
const previewLoader=__vectorAssetLoader.createVectorAssetLoader({fetch:globalThis.fetch.bind(globalThis),maxEntries:1});
const previewVector=await previewLoader.load(new URL('../../${assetUrl}',location.href),{sourcePath:'${sourcePath}',expectedSha256:'${sha256}',maxBytes:${maxBytes},curveSegments:${curveSegments},includeSourcePaths:false});`;
const code=previewBootstrap+'\n'+engine+'\n'+historical+'\n'+preview;
const check=spawnSync(process.execPath,['--input-type=module','--check'],{input:code,encoding:'utf8'});
if(check.status)throw Error(check.stderr);
const html=readFileSync('previews/companion-combat/shell.html','utf8').replace('<!-- DIGMORI_PREVIEW -->',()=>'<script type="module">\n'+code+'\n</script>');
mkdirSync('dist/previews/companion-combat',{recursive:true});
writeFileSync('dist/previews/companion-combat/index.html',html);
console.log('Built preview only: dist/previews/companion-combat/index.html');
